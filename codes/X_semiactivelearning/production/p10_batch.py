def download_foundation():
    os.environ['XDG_CACHE_HOME']=str(MLIP/'outputsfull/.cache')
    os.environ.setdefault('TORCH_FORCE_NO_WEIGHTS_ONLY_LOAD','1')
    from mace.calculators.foundations_models import download_mace_polar_checkpoint, polar_model_urls
    from importlib.metadata import version
    return Path(download_mace_polar_checkpoint('polar-1-l')), {'alias':'polar-1-l','url':polar_model_urls['polar-1-l'],'mace_package_version':version('mace-torch')}


def cache_foundation(plan):
    campaign=configure(plan)
    if plan.get('model_mode')!='foundation':
        raise ValueError('Foundation caching is only for an explicit foundation-model plan')
    if (campaign.OUT/'model_binding.json').exists():
        model,record=binding(plan); print(record); return
    source,provenance=download_foundation()
    digest=sha(source)
    lock=plan.get('foundation_checkpoint')
    if lock and digest!=lock['sha256']:
        raise ValueError('Downloaded foundation bytes differ from the prepared checkpoint lock')
    plan['foundation_checkpoint']={'alias':'polar-1-l','url':provenance['url'],'sha256':digest}
    write_json(MLIP/plan['plan_relative'],plan)
    target=campaign.OUT/'model'; target.mkdir(exist_ok=False)
    frozen=target/'foundation_polar_1_l.model'; shutil.copy2(source,frozen)
    provenance.update(model_mode='foundation',foundation_model='polar-1-l',sha256=sha(frozen),source_cache=str(source))
    write_json(target/'foundation_provenance.json',provenance)
    record={'model_mode':'foundation','foundation_model':'polar-1-l','model_relative':str(frozen.relative_to(MLIP)),
            'sha256':sha(frozen),'provenance_relative':str((target/'foundation_provenance.json').relative_to(MLIP)),
            'provenance_sha256':sha(target/'foundation_provenance.json')}
    write_json(campaign.OUT/'model_binding.json',record)
    write_json(campaign.OUT/'model_lineage.json',{'current_model':str(frozen),'root_model':'polar-1-l','history':[],'initialization_evidence':record})
    notebook(f'Foundation polar-1-l frozen: {record}', 'No model inference or MD run; all ten jobs will verify the same checkpoint bytes.',
             'Inspect resources and run-code before any later submission.', 'Removes fine-tuned-model ambiguity and parallel download races.', 'Foundation initialization selected by user; replica seed alone varies within this ensemble.')
    print(record)


def bind_model(args, plan):
    campaign=configure(plan)
    if plan.get('model_mode')=='foundation':
        raise ValueError('This plan explicitly selects foundation polar-1-l; use cache-foundation')
    model=args.model.expanduser().resolve()
    if not model.is_file() or not model.stat().st_size:
        raise FileNotFoundError(model)
    metadata=args.metadata or model.parent.parent/'run_metadata.json'
    metadata=metadata.expanduser().resolve()
    provenance=json.loads(metadata.read_text())
    foundation=provenance.get('arguments',{}).get('foundation_model')
    if foundation != 'polar-1-l':
        if provenance.get('root_model') != 'polar-1-l':
            raise ValueError('Need training metadata or lineage proving polar-1-l initialization; never infer size from a filename')
        if not any(Path(entry.get('model','')).name == model.name for entry in provenance.get('history',[])):
            raise ValueError('Chosen checkpoint is absent from the supplied lineage')
    if (campaign.OUT/'model_binding.json').exists():
        raise FileExistsError('Model already frozen for this ensemble; prepare a new batch to change it')
    target=campaign.OUT/'model'; target.mkdir()
    shutil.copy2(model,target/'fine_tuned.model')
    shutil.copy2(metadata,target/'training_provenance.json')
    record={'model_relative':str((target/'fine_tuned.model').relative_to(MLIP)), 'sha256':sha(target/'fine_tuned.model'),
            'foundation_model':'polar-1-l','checkpoint_source':str(model),'training_metadata_source':str(metadata),
            'training_metadata_sha256':sha(target/'training_provenance.json'), 'training_reference_method':provenance.get('reference_method')}
    write_json(campaign.OUT/'model_binding.json',record)
    write_json(campaign.OUT/'model_lineage.json',{'current_model':str(target/'fine_tuned.model'), 'root_model':'polar-1-l','history':[],'initialization_evidence':record})
    notebook(f'Frozen fine-tuned checkpoint {record}', 'Training reference method recorded; MD sampling provenance does not authorize mixing old DFT labels.',
             'Run/check ten identically configured replicas with these frozen bytes.', 'Isolates seed sensitivity at 10 GPa.', 'Replica seed only.')
    print(record)


